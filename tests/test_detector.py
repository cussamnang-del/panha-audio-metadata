def test_schedule_detection_runs_off_thread_and_emits_result(
    qapp, tmp_path: Path
):
    pool = QThreadPool()
    pool.setMaxThreadCount(2)

    src = tmp_path / "song.mp3"
    src.write_bytes(b"")

    received: list[tuple[str, DetectorResult]] = []

    def fake_detect(_path: str) -> DetectorResult:
        return DetectorResult(
            platform="Suno", platform_score=95, confidence=90,
            verdict=VERDICT_AI, is_ai=True, reason="stubbed",
        )

    schedule_detection(
        str(src),
        lambda p, r: received.append((p, r)),
        pool=pool,
        detect_fn=fake_detect,
    )

    pool.waitForDone(5000)
    qapp.processEvents()

    assert len(received) == 1
    assert received[0][0] == str(src)
    assert received[0][1].is_ai is True
    assert received[0][1].platform == "Suno"


def test_dialog_apply_detection_result_renders_red_for_ai(qapp, tmp_path: Path):
    """Regression: dropping in a Suno-tagged file must end up showing the
    red 'AI-GENERATED' verdict in the table, not the analyzing
    placeholder."""
    from panha.dialogs.ai_detector_dialog import _COLOR_AI, AIDetectorDialog

    dlg = AIDetectorDialog(schedule_fn=lambda *a, **k: None)
    src = tmp_path / "suno_track.mp3"
    src.write_bytes(b"")
    assert dlg.add_paths([str(src)]) == 1

    dlg.apply_detection_result(
        0,
        DetectorResult(
            platform="Suno",
            platform_score=100,
            confidence=85,
            verdict=VERDICT_AI,
            is_ai=True,
            reason="Found Suno markers",
        ),
    )

    assert dlg.table.item(0, 1).text() == "Suno 100%"
    assert dlg.table.item(0, 2).text() == "85% AI"
    assert dlg.table.item(0, 3).text() == VERDICT_AI

    # Colour: AI cells must use the red AI palette.
    fg_brush = dlg.table.item(0, 3).foreground()
    assert fg_brush.color().rgb() == _COLOR_AI.rgb()
    # Verdict cell must render bold to match the screenshot.
    assert dlg.table.item(0, 3).font().bold() is True

    # Tooltip on the analysis cells surfaces the detector's reason so
    # users can click to see *why* a track was flagged.
    assert dlg.table.item(0, 3).toolTip() == "Found Suno markers"

    dlg.deleteLater()


