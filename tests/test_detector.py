def test_detect_soft_marker_with_uuid_boosts_confidence(tmp_path: Path):
    """A "suno" mention + UUID-shaped ID should outrank a bare keyword hit."""
    plain = tmp_path / "Suno Track.mp3"
    plain.write_bytes(b"")
    plain_result = detect_ai_audio(
        plain, read_metadata_fn=lambda *_a, **_k: {}
    )

    with_uuid = tmp_path / "Suno f4a1c2bd-9d4b-4a5e-9c7c-8f3f8c5b22a1.mp3"
    with_uuid.write_bytes(b"")
    uuid_result = detect_ai_audio(
        with_uuid, read_metadata_fn=lambda *_a, **_k: {}
    )

    assert plain_result.verdict == VERDICT_AI
    assert uuid_result.verdict == VERDICT_AI
    # The UUID nudge gives the second file a higher score than the
    # plain-keyword-only file.
    assert uuid_result.platform_score > plain_result.platform_score
    assert uuid_result.confidence > plain_result.confidence
    assert "uuid" in uuid_result.reason.lower()


def test_detect_stacks_multiple_suno_markers(tmp_path: Path):
    """Several strong markers should push the score higher than one alone."""
    src = tmp_path / "track.mp3"
    src.write_bytes(b"")
    single = detect_ai_audio(
        src, read_metadata_fn=lambda *_a, **_k: {"comment": "https://suno.com/song/x"}
    )
    stacked = detect_ai_audio(
        src,
        read_metadata_fn=lambda *_a, **_k: {
            "comment": "https://suno.com/song/x",
            "tenc": "Suno v4",
            "tpub": "Suno AI",
        },
    )
    assert stacked.platform_score >= single.platform_score
    assert stacked.confidence >= single.confidence


